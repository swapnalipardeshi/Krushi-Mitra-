-- 1. Enable Required Extensions
create extension if not exists "uuid-ossp";
create extension if not exists "pgcrypto";

-- 2. Farmers Table
create table if not exists public.farmers (
    id text primary key,
    name text not null,
    photo_url text,
    state text not null default 'Maharashtra',
    district text not null default 'Nashik',
    land_size numeric not null default 2.5,
    crops_grown text[] default array['Wheat', 'Tomato', 'Soyabean', 'Onion'],
    preferred_language text default 'hi',
    soil_type text default 'Black Soil (Regur)',
    irrigation_source text default 'Drip Irrigation',
    weather_alerts boolean default true,
    scheme_alerts boolean default true,
    price_alerts boolean default false,
    fcm_token text,
    created_at timestamptz default timezone('utc'::text, now()) not null
);

-- Ensure fcm_token column exists if table was previously created
do $$ 
begin 
    if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'farmers' and column_name = 'fcm_token') then
        alter table public.farmers add column fcm_token text;
    end if;
end $$;

-- 3. Farm Diary Table
create table if not exists public.farm_diary (
    id uuid primary key default gen_random_uuid(),
    farmer_id text not null references public.farmers(id) on delete cascade,
    entry_date timestamptz not null default timezone('utc'::text, now()),
    activity text not null,
    category text not null,
    cost numeric not null default 0.0,
    is_expense boolean not null default true,
    notes text,
    created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 4. Marketplace Listings Table
create table if not exists public.marketplace_listings (
    id uuid primary key default gen_random_uuid(),
    farmer_id text not null references public.farmers(id) on delete cascade,
    farmer_name text not null,
    title text not null,
    crop_type text not null,
    quantity numeric not null,
    unit text not null default 'kg',
    price_per_unit numeric not null,
    location text not null,
    phone text not null,
    image_url text,
    status text not null default 'active',
    created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 5. Community Posts Table
create table if not exists public.community_posts (
    id uuid primary key default gen_random_uuid(),
    farmer_id text not null references public.farmers(id) on delete cascade,
    author_name text not null,
    content text not null,
    likes integer not null default 0,
    image_url text,
    created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 6. Mandi Market Prices Table
create table if not exists public.mandi_prices (
    id bigint generated by default as identity primary key,
    commodity text not null,
    variety text not null default 'Standard',
    market text not null,
    district text not null,
    state text not null,
    min_price numeric not null,
    max_price numeric not null,
    modal_price numeric not null,
    arrival_date date not null default current_date
);

-- Ensure variety column exists if table was previously created
do $$ 
begin 
    if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'mandi_prices' and column_name = 'variety') then
        alter table public.mandi_prices add column variety text not null default 'Standard';
    end if;
end $$;

-- 7. Conflict Audit Logs Table
create table if not exists public.conflict_audit_logs (
    id uuid primary key default gen_random_uuid(),
    farmer_name text not null,
    location text not null,
    activity_type text not null,
    conflict_title text not null,
    conflict_reason text not null,
    rain_probability numeric not null,
    user_reason text not null,
    raw_inputs jsonb,
    created_at timestamptz default timezone('utc'::text, now()) not null
);

