-- Strict Farmers Policies
create policy "farmers_select_policy" on public.farmers 
    for select using (true);

create policy "farmers_insert_policy" on public.farmers 
    for insert with check (auth.uid()::text = id or auth.role() = 'anon');

create policy "farmers_update_policy" on public.farmers 
    for update using (auth.uid()::text = id or auth.role() = 'anon');

create policy "farmers_delete_policy" on public.farmers 
    for delete using (auth.uid()::text = id);

-- Strict Farm Diary Policies (Private to owner)
create policy "diary_select_policy" on public.farm_diary 
