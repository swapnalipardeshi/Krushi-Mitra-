create policy "diary_insert_policy" on public.farm_diary 
    for insert with check (auth.uid()::text = farmer_id or auth.role() = 'anon');

create policy "diary_update_policy" on public.farm_diary 
    for update using (auth.uid()::text = farmer_id or auth.role() = 'anon');

create policy "diary_delete_policy" on public.farm_diary 
    for delete using (auth.uid()::text = farmer_id or auth.role() = 'anon');

-- Strict Marketplace Policies (Public read, seller-only write/update/delete)
