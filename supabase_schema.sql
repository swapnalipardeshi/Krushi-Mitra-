-- Enable UUID extension
create extension if not exists "uuid-ossp";

-- 1. Farmers Profile Table
create table if not exists public.farmers (
    id text primary key, -- Can be Supabase Auth user ID or guest/local ID
    name text not null,
    photo_url text,
    state text not null default 'Maharashtra',
    district text not null default 'Nashik',
    land_size numeric not null default 2.5,
    crops_grown text[] default array['Wheat', 'Tomato', 'Soyabean', 'Onion'],
    preferred_language text default 'hi',
    soil_type text default 'Black Soil (Regur)',
    irrigation_source text default 'Drip Irrigation',
    weather_alerts boolean default true,
    scheme_alerts boolean default true,
    price_alerts boolean default false,
    created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 2. Farm Diary Entries (Expenses & Activities)
create table if not exists public.farm_diary (
    id uuid primary key default gen_random_uuid(),
    farmer_id text not null references public.farmers(id) on delete cascade,
    entry_date timestamptz not null default timezone('utc'::text, now()),
    activity text not null,
    category text not null,
    cost numeric not null default 0.0,
    is_expense boolean not null default true,
    notes text,
    created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 3. Marketplace Listings (Farmer-to-Farmer & Buyer trade)
create table if not exists public.marketplace_listings (
    id uuid primary key default gen_random_uuid(),
    farmer_id text not null references public.farmers(id) on delete cascade,
    farmer_name text not null,
    title text not null,
    crop_type text not null,
    quantity numeric not null,
    unit text not null default 'kg',
    price_per_unit numeric not null,
    location text not null,
    phone text not null,
    image_url text,
    status text not null default 'active',
    created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 4. Community Posts
create table if not exists public.community_posts (
    id uuid primary key default gen_random_uuid(),
    farmer_id text not null references public.farmers(id) on delete cascade,
    author_name text not null,
    content text not null,
    likes integer not null default 0,
    image_url text,
    created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 5. Mandi Market Prices Cache
create table if not exists public.mandi_prices (
    id bigint generated by default as identity primary key,
    commodity text not null,
    market text not null,
    district text not null,
    state text not null,
    min_price numeric not null,
    max_price numeric not null,
    modal_price numeric not null,
    arrival_date date not null default current_date
);

-- ====================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- ====================================================================
-- Enable RLS
alter table public.farmers enable row level security;
alter table public.farm_diary enable row level security;
alter table public.marketplace_listings enable row level security;
alter table public.community_posts enable row level security;
alter table public.mandi_prices enable row level security;

-- Public read policies (Allows all farmers and guests to view data)
create policy "Allow public read farmers" on public.farmers for select using (true);
create policy "Allow public insert/update farmers" on public.farmers for all using (true);

create policy "Allow public read diary" on public.farm_diary for select using (true);
create policy "Allow public insert/update diary" on public.farm_diary for all using (true);

create policy "Allow public read marketplace" on public.marketplace_listings for select using (true);
create policy "Allow public write marketplace" on public.marketplace_listings for all using (true);

create policy "Allow public read posts" on public.community_posts for select using (true);
create policy "Allow public write posts" on public.community_posts for all using (true);

create policy "Allow public read mandi" on public.mandi_prices for select using (true);
create policy "Allow public write mandi" on public.mandi_prices for all using (true);

-- Create storage bucket for plant disease photos and crop images
insert into storage.buckets (id, name, public) 
values ('krushi-uploads', 'krushi-uploads', true)
on conflict (id) do nothing;

create policy "Allow public uploads to krushi-uploads"
on storage.objects for insert with check (bucket_id = 'krushi-uploads');

create policy "Allow public read from krushi-uploads"
on storage.objects for select using (bucket_id = 'krushi-uploads');

